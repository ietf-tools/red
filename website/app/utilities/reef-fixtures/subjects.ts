// The other names a subject answers to. Only one subject has any, because the sheet carries none and
// an alias is worth having in the fixture only so that the redirect it causes is reachable.
const ALIASES_BY_SLUG: Record<string, string[]> = {
  cryptography: ['crypto']
}

const subjectsBySlug = new Map(subjectsFixture.map((subject) => [subject.slug, subject]))

const subjectNamed = (slug: string): Subject => {
  const subject = subjectsBySlug.get(slug)
  if (subject === undefined) {
    throw new Error(`No subject fixture named ${slug}`)
  }
  return subject
}

// The detail answer for a subject in the vocabulary, assembled from the list rather than written out
// a second time: a name and a count that disagreed between the two answers would be a fixture
// describing a Reef that does not exist.
const detailFor = (subject: Subject): SubjectDetail => ({
  ...subject,
  retired: false,
  children: subjectsFixture.filter(({ parent }) => parent === subject.slug).map(({ slug }) => slug),
  aliases: ALIASES_BY_SLUG[subject.slug] ?? [],
  documents: DOCUMENTS_BY_SLUG[subject.slug] ?? []
})

// A subject that holds documents of its own and has subjects beneath it holding more, which is the
// case where the two counts differ and the page has to say so.
export const subjectDetailFixture = detailFor(subjectNamed('compression'))

// A subject at the bottom of its branch: everything counted against it is on the page.
export const leafSubjectDetailFixture = detailFor(subjectNamed('gzip'))

// A root that carries nothing itself. None of the fourteen do; they are headings over their
