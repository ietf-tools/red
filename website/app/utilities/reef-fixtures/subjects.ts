export const subjectAliasFixture: SubjectAlias = {
  slug: 'crypto',
  alias_of: 'cryptography'
}

/**
 * What Reef answers /api/reef/subjects/<slug>/ with, or undefined for a slug it has never heard of,
 * which the caller turns into a 404.
 *
 * Every subject in the vocabulary is answerable, so a dev server can be clicked through the whole
 * tree. The three invented slugs are answered first because they are not in it.
 */
export const subjectDetailFor = (slug: string): SubjectDetailOrRedirect | undefined => {
  if (slug === retiredSubjectFixture.slug) return retiredSubjectFixture
  if (slug === subjectAliasFixture.slug) return subjectAliasFixture
  if (slug === emptySubjectDetailFixture.slug) return emptySubjectDetailFixture

  const subject = subjectsBySlug.get(slug)
  return subject === undefined ? undefined : detailFor(subject)
}

// What the `empty` scenario answers a detail request with: the subject is there and is nothing's
// subject yet. A redirect — retired or alias — has no membership to empty, so it is left as it is.
export const emptied = (subject: SubjectDetailOrRedirect): SubjectDetailOrRedirect =>
  isRetiredSubject(subject) || isSubjectAlias(subject) ? subject : { ...subject, documents: [] }
