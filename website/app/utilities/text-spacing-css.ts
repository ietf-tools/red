// Builds the two stylesheets that depend on the text spacing step tables. Pure so a unit test can
// compare the output with the committed files; scripts/generate-text-spacing-css.ts writes them.
//
// This file is imported by a Node script, so it must not use Nuxt auto-imports or `~` aliases.
import {
  LETTER_SPACING_VALUES,
  PARAGRAPH_SPACING_VALUES,
  WORD_SPACING_RATIO,
  WORD_SPACING_VALUES
} from './text-spacing.ts'

// The word size groupings the precomputer labels breaks with, in em. Must match the precomputer.
const WORD_SIZE_TIERS_EM = [4, 6, 8, 10, 12, 16, 24]

// Headroom the unscaled thresholds already carry over a tier's ceiling, for a substituted font.
const SAFETY_FACTOR = 1.2

// Extra width the touch preview button adds to a citation. A custom property cannot be used in a
// container query condition, so the allowance is repeated here as a literal.
const PREVIEW_BUTTON_ALLOWANCE_REM = 2.66

// Letter spacing adds its amount once per character, so a word of width W em grows by about
// W / (average advance) times the spacing. A low average over-counts characters, which only ever
// keeps more breaks, never fewer. The word-breaks e2e test checks this against real documents.
const AVERAGE_ADVANCE_EM = 0.4

// A citation holds a space or two, and word spacing widens each of them.
const CITATION_SPACES = 2

const GENERATED_NOTICE =
  'Generated by scripts/generate-text-spacing-css.ts from app/utilities/text-spacing.ts. Do not edit by hand.'

// Rounded up so rounding can only make a threshold stricter.
const roundUp = (value: number): number => Math.ceil(value * 100) / 100

const formatEm = (value: number): string => `${roundUp(value)}em`

export const wordBreakThresholdEm = (tierEm: number, letterSpacingEm: number): number =>
  SAFETY_FACTOR * tierEm * (1 + letterSpacingEm / AVERAGE_ADVANCE_EM)

// Word spacing is never below the ratio times letter spacing, so the letter spacing in play is at
// most the word spacing divided by the ratio. Using that bound lets a citation's threshold depend on
// the word step alone.
export const citationThresholdEm = (tierEm: number, wordSpacingEm: number): number =>
  SAFETY_FACTOR * tierEm * (1 + wordSpacingEm / WORD_SPACING_RATIO / AVERAGE_ADVANCE_EM) +
  CITATION_SPACES * wordSpacingEm

export const generateTailwindCss = (): string => {
  const tokens = LETTER_SPACING_VALUES.map((value, index) =>
    index === 0 ? '' : `  --tracking-reader-${index}: ${value}em;\n`
  ).join('')
  const wordUtilities = WORD_SPACING_VALUES.map((value, index) =>
    index === 0 ? '' : `@utility word-spacing-reader-${index} {\n  word-spacing: ${value}em;\n}\n\n`
  ).join('')
  const paragraphUtilities = PARAGRAPH_SPACING_VALUES.map(
    (value, index) => `@utility paragraph-spacing-reader-${index + 1} {\n  --paragraph-spacing: ${value}em;\n}\n`
  ).join('\n')

  return `/* ${GENERATED_NOTICE} */\n\n@theme {\n${tokens}}\n\n${wordUtilities}${paragraphUtilities}`
}

export const generateWordBreakCss = (): string => {
  const breakRules = LETTER_SPACING_VALUES.flatMap((letterEm, step) =>
    step === 0
      ? []
      : WORD_SIZE_TIERS_EM.map(
          (tier) =>
            `@container (min-width: ${formatEm(wordBreakThresholdEm(tier, letterEm))}) {\n  &[data-letter-step='${step}'] wbr.wordsize-${tier} {\n    display: none;\n  }\n}\n`
        )
  )

  const citationRules = WORD_SPACING_VALUES.flatMap((wordEm, step) => {
    if (step === 0) {
      return []
    }
    const scope = `&[data-word-step='${step}'] .reference-citation`
    const plain = WORD_SIZE_TIERS_EM.map(
      (tier) =>
        `@container (min-width: ${formatEm(citationThresholdEm(tier, wordEm))}) {\n  ${scope}.wordsize-${tier} {\n    white-space: nowrap;\n  }\n}\n`
    )
    const resets = `${WORD_SIZE_TIERS_EM.map((tier) => `${scope}.wordsize-${tier}:has([data-rfc-preview-button])`).join(',\n')} {\n  white-space: normal;\n}\n`
    const withButton = WORD_SIZE_TIERS_EM.map(
      (tier) =>
        `@container (min-width: calc(${formatEm(citationThresholdEm(tier, wordEm))} + ${PREVIEW_BUTTON_ALLOWANCE_REM}rem)) {\n  ${scope}.wordsize-${tier}:has([data-rfc-preview-button]) {\n    white-space: nowrap;\n  }\n}\n`
    )
    return [...plain, resets, ...withButton]
  })

  return `/* ${GENERATED_NOTICE}

   The unscaled word-break and citation rules are in xml2rfc.css and apply while no spacing step is
   set. These repeat them for each step with thresholds widened by the width the spacing adds, so a
   word is only held whole where it still fits once spaced. They are scoped by the step attributes
   RFCDocumentBody puts on the document wrapper. Letter spacing widens words, so it drives the break
   rules. Word spacing widens the gaps in a citation, so it drives the citation rules. */\n\n${breakRules.join('\n')}\n${citationRules.join('\n')}`
}
